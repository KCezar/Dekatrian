  /// Retorna a data do Ano-Novo Chinês (1º dia do 1º mês lunar).
  static DateTime chineseNewYear(int year) => _lunarToGregorian(year, 1, 1);

  /// Festival do Barco-Dragão (5º dia do 5º mês lunar).
  static DateTime dragonBoatFestival(int year) => _lunarToGregorian(year, 5, 5);

  /// Festival do Meio-Outono (15º dia do 8º mês lunar).
  static DateTime midAutumnFestival(int year) => _lunarToGregorian(year, 8, 15);

  static DateTime _lunarToGregorian(int year, int month, int day) {
    if (year < _minYear || year > _maxYear) {
      throw ArgumentError('Ano fora do intervalo $_minYear–$_maxYear');
    }
    final info = _yearInfo[year - _minYear];
    // Converter strings para inteiros
    final int leapMonth = int.parse(info[0]);
    final int lunarNewYearMonth = int.parse(info[1]);
    final int lunarNewYearDay = int.parse(info[2]);
    // Máscara de bits como string de '0'/'1'
    final String maskStr = info[3].padLeft(16, '0');

    // Offset de dias desde o início do ano lunar até a data desejada
    int offset = day - 1;
    for (int m = 1; m < month; m++) {
      // cada caractere em maskStr representa 1 mês: '1' = 30 dias, '0' = 29 dias
      offset += (maskStr[m - 1] == '1') ? 30 : 29;
      // se for o mês extra, usar o próximo bit
      if (m == leapMonth) {
        offset += (maskStr[m] == '1') ? 30 : 29;
      }
    }

    // Data base do Ano-Novo lunar em gregoriano
    final baseDate = DateTime(year, lunarNewYearMonth, lunarNewYearDay);
    return baseDate.add(Duration(days: offset));
  }
